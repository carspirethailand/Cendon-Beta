/* 3) จับคู่ช่างอัตโนมัติ — เลือกให้เลยว่าใครเหมาะที่สุด พร้อมบอกเหตุผล
      บอกเหตุผลเสมอ เพราะระบบที่เลือกให้โดยไม่บอกว่าทำไม ไม่มีใครกล้าเชื่อ */
function match(o){
  o=o||{};
  const l=search({q:o.symptom||"",here:o.here,cat:o.urgent?"quick":null,limit:20});
  if(!l.length)return null;
  const scored=l.map(t=>{
    let sc=0; const why=[];
    if(t.dist!=null&&t.dist<=15){ sc+=28; why.push("อยู่ห่างแค่ "+t.dist+" กม.") }
    else if(t.dist!=null&&t.dist<=40){ sc+=14; why.push("ห่าง "+t.dist+" กม.") }
    if(t.rating>=4.8){ sc+=22; why.push("คะแนน "+t.rating+" จาก "+t.jobs+" งาน") }
    else if(t.rating>=4.5){ sc+=12; why.push("คะแนน "+t.rating) }
    if(t.verified){ sc+=16; why.push("ผ่านการตรวจสอบครบทุกด่าน") }
    if(o.urgent&&t.urgent){ sc+=20; why.push("รับงานด่วน ตอบเฉลี่ย "+t.reply+" นาที") }
    if(o.mobile&&t.mobile){ sc+=18; why.push("ออกไปหาถึงที่ได้") }
    if(o.budget&&t.from<=o.budget){ sc+=12; why.push("ราคาเริ่มต้นอยู่ในงบ") }
    if(t.warranty>=30){ sc+=8; why.push("รับประกัน "+t.warranty+" วัน") }
    const car=o.car||{};
    const br=(car.make||"").toLowerCase();
    if(br&&(t.brands||[]).some(x=>x.toLowerCase().indexOf(br)>=0)){
      sc+=15; why.push("ทำ "+car.make+" เป็นประจำ");
    }
    return Object.assign({},t,{fit:sc,why});
  }).sort((a,b)=>b.fit-a.fit);
  return {best:scored[0],others:scored.slice(1,4),all:scored};
}

